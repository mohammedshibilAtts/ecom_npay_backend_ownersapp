import mongoose, { Schema } from 'mongoose';

const giftinwardsSchema = new mongoose.Schema({
    gift_vendorid:{
        type:mongoose.Schema.Types.ObjectId,
        required:true,
        ref:'GiftVendor'
    },
    invoice_no:{
        type:String,
        required:true
    },
    id_gift:{
        type:mongoose.Schema.Types.ObjectId,
        required:true,
        ref:'GiftItem'
    },
    barcode:{
        type:Number,
    },
    qty:{
        type:Number,
        required:true
    },
    inward_qty:{
      type:Number,
      required:true
    },
    price:{
        type:Number,
        required:true
    },
    id_branch:{
        type:mongoose.Schema.Types.ObjectId,
        required:true,
        ref:'Branch'
    },
    active:{
        type:Boolean,
        default:true
    },
    is_deleted:{
        type:Boolean,
        default:false
    },
    created_by:{
        type:mongoose.Schema.Types.ObjectId,
        required:true,
        ref:'Employee'
    },
    modified_by:{
        type:mongoose.Schema.Types.ObjectId,
        required:true,
        ref:'Employee'
    },
    gst_percenty:{
        type:Number,
        required:true
    },
    cus_sellprice:{
        type:Number,
        required:true
    },
    total:{
      type:Number,
      default:0
    }
},{
    timestamps:true
});

export default mongoose.model('GiftInwards',giftinwardsSchema)